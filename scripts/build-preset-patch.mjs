/**
 * Regenerate `presets/pm.patch.yml` from `preset/agent.cordis.yml`.
 *
 * Why this exists: on Desktop 0.2.0 an agent preset is an ordinary composition
 * row — a `@deepseek-ai/dsh-agent-preset` entry whose `config.plugins` is the
 * child list — and the shipped presets live in `presets/*.patch.yml` files
 * declared by the bundle's `dsh.bundle.patch`. The `$DSH_HOME/.agent-presets/
 * <id>/` directory this package was originally written against is a 0.1.x
 * convention that nothing reads any more, which is why the preset picker showed
 * no `pm` mode even with the plugin row active.
 *
 * `preset/agent.cordis.yml` stays the source of truth (it is what
 * scripts/sync-preset.mjs diffs against the live copy, and it carries the
 * doctrine comments), so this script wraps it rather than replacing it: the
 * patch file is generated, and is expected to be regenerated, never hand-edited.
 *
 * Usage:
 *   node scripts/build-preset-patch.mjs           write the patch file
 *   node scripts/build-preset-patch.mjs --check   fail if the file is stale
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");
const SOURCE = path.join(ROOT, "preset", "agent.cordis.yml");
const TARGET = path.join(ROOT, "presets", "pm.patch.yml");

// The row's metadata. `order: 9` places `pm` after the shipped presets
// (standard 1, ptc 2, minimal 3, cordis 4) without colliding with them.
const ROW_ID = "preset-pm";
const PRESET_ID = "pm";
const PRESET_ORDER = 9;
const PRESET_NAME = "总控模式";
const PRESET_DESCRIPTION =
  "派单台型编排 Agent：每个用户诉求交给一个专家 Agent 整条解决，按领域把同类后续诉求交回同一个专家，" +
  "并把领域/任务/专家/令牌状态写进 Web GUI 的项目看板。";

const HEADER = [
  "# Agent preset pm (总控模式): the PM Mode dispatcher declaration.",
  "#",
  "# GENERATED by scripts/build-preset-patch.mjs from preset/agent.cordis.yml.",
  "# Do not edit by hand; edit the source preset and regenerate.",
  "#",
  "# Declared exactly like the presets dsh-web-app ships: one",
  "# `@deepseek-ai/dsh-agent-preset` row whose `config.plugins` is the child",
  "# composition. On Desktop 0.2.0 a preset IS a composition row — the",
  "# `$DSH_HOME/.agent-presets/<id>/` directory this package originally targeted",
  "# is a 0.1.x-era convention that nothing reads any more, which is why the",
  "# preset picker showed no `pm` mode with the plugin row active.",
  "#",
  "# The row id follows the shipped convention `preset-<id>`.",
  "- insert:",
  `    - id: ${ROW_ID}`,
  "      name: '@deepseek-ai/dsh-agent-preset'",
  "      config:",
  `        id: ${PRESET_ID}`,
  `        order: ${PRESET_ORDER}`,
  `        name: ${PRESET_NAME}`,
  `        description: ${PRESET_DESCRIPTION}`,
  "        plugins:",
];

/** Wrap the source list one level deeper so it becomes `config.plugins`. */
function build() {
  const rows = readFileSync(SOURCE, "utf8").split(/\r?\n/);
  const indented = rows.map((line) => (line === "" ? "" : "          " + line));
  return HEADER.concat(indented).join("\n") + "\n";
}

const generated = build();
const check = process.argv.includes("--check");

if (check) {
  let current = null;
  try {
    current = readFileSync(TARGET, "utf8");
  } catch {
    console.error("presets/pm.patch.yml is missing — run: node scripts/build-preset-patch.mjs");
    process.exit(1);
  }
  if (current !== generated) {
    console.error("presets/pm.patch.yml is STALE — run: node scripts/build-preset-patch.mjs");
    process.exit(1);
  }
  console.log("presets/pm.patch.yml is up to date");
  process.exit(0);
}

mkdirSync(path.dirname(TARGET), { recursive: true });
writeFileSync(TARGET, generated, "utf8");
console.log("wrote " + path.relative(ROOT, TARGET) + " (" + generated.length + " bytes)");
